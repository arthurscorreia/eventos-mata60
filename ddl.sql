CREATE TABLE tbl_pessoa
(
    cp_id_pessoa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nm_pessoa VARCHAR NOT NULL,
    cpf_pessoa CHAR(11),
    passaporte_pessoa VARCHAR,
    email_pessoa VARCHAR NOT NULL,
    dt_nascimento DATE,
    pais_pessoa CHAR(3) NOT NULL,
    /* associacao_vigente (calculado) BOOLEAN NOT NULL,
       será calculado no SELECT */
    uf_pessoa CHAR(2) NOT NULL,

    UNIQUE (cpf_pessoa),
    UNIQUE (passaporte_pessoa),
    UNIQUE (email_pessoa)
);

CREATE TABLE tbl_evento
(
    cp_id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano_evento INT NOT NULL,
    dt_inicio_evento DATE NOT NULL,
    dt_fim_evento DATE NOT NULL,
    modalidade_evento VARCHAR NOT NULL,

    nm_lote_1 VARCHAR NOT NULL,
    dt_inicio_lote_1 DATE NOT NULL,
    dt_fim_lote_1 DATE NOT NULL,
    vl_preco_base_lote_1 NUMERIC(16,2) NOT NULL,

    nm_lote_2 VARCHAR,
    dt_inicio_lote_2 DATE,
    dt_fim_lote_2 DATE,
    vl_preco_base_lote_2 NUMERIC(16,2),

    nm_lote_3 VARCHAR,
    dt_inicio_lote_3 DATE,
    dt_fim_lote_3 DATE,
    vl_preco_base_lote_3 NUMERIC(16,2),

    nm_lote_4 VARCHAR,
    dt_inicio_lote_4 DATE,
    dt_fim_lote_4 DATE,
    vl_preco_base_lote_4 NUMERIC(16,2),

    sg_evento VARCHAR NOT NULL,
    nm_evento VARCHAR NOT NULL,
    ds_evento VARCHAR NOT NULL,
    cidade_evento VARCHAR NOT NULL,
    uf_evento CHAR(2) NOT NULL,
    pais_evento CHAR(3) NOT NULL,
    edicao_evento VARCHAR NOT NULL,
    tp_evento VARCHAR NOT NULL,
    ce_evento_agregador INT
);

CREATE TABLE tbl_categoria_inscricao
(
    cp_id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fator_mult_preco NUMERIC(8,7) NOT NULL DEFAULT 1.0,
    nm_categoria VARCHAR NOT NULL,
    ds_categoria VARCHAR NOT NULL,
    ce_evento INT NOT NULL
);

CREATE TABLE tbl_inscricao
(
    cp_id_inscricao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /* Atributos calculados: serão obtidos por consultas SELECT */
    /* status_inscricao VARCHAR NOT NULL DEFAULT 'PENDENTE', */
    /* vl_total_inscricao NUMERIC(16,2) NOT NULL DEFAULT 0, */
    /* dt_confirmacao (calculado) TIMESTAMP, */

    dt_inscricao TIMESTAMP NOT NULL,
    ce_categoria INT NOT NULL,
    ce_pessoa INT NOT NULL
);

CREATE TABLE tbl_atividade
(
    cp_id_atividade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vl_atividade NUMERIC(16,2) NOT NULL DEFAULT 0.0,
    dt_inicio TIMESTAMP NOT NULL,
    dt_fim TIMESTAMP NOT NULL,
    nm_atividade VARCHAR NOT NULL,
    tp_atividade VARCHAR NOT NULL,
    ce_categoria INT NOT NULL
);

CREATE TABLE tbl_pagamento
(
    cp_id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vl_pagamento NUMERIC(16,2) NOT NULL,
    dt_criacao TIMESTAMP NOT NULL,
    dt_confirmacao TIMESTAMP,

    /* status_pagamento (calculado):
       será obtido por consulta SELECT */

    cd_transacao VARCHAR,
    tp_pagamento VARCHAR NOT NULL,
    ce_pagamento_reembolsado INT,
    ce_item_financeiro INT NOT NULL,

    UNIQUE (cd_transacao),
    UNIQUE (ce_pagamento_reembolsado)

    /*
    Caso decidam implementar o status como coluna gerada:

    status_pagamento VARCHAR(20) GENERATED ALWAYS AS (
        CASE
            WHEN dt_confirmacao IS NOT NULL THEN 'CONFIRMADO'
            ELSE 'PENDENTE'
        END
    ) STORED
    */
);

CREATE TABLE tbl_associacao_sbtc
(
    ce_pessoa INT NOT NULL,
    dt_inicio_associacao DATE NOT NULL,
    dt_fim_associacao DATE NOT NULL,

    PRIMARY KEY (
        ce_pessoa,
        dt_inicio_associacao,
        dt_fim_associacao
    )
);

CREATE TABLE tbl_item_financeiro
(
    cp_id_item_financeiro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /* dt_pagamento (calculado) TIMESTAMP, */
    /* vl_pago (calculado) NUMERIC(16,2), */

    dt_cancelamento TIMESTAMP,
    ce_inscricao INT NOT NULL,
    ds_item_financeiro VARCHAR NOT NULL,
    vl_item_financeiro NUMERIC(16,2) NOT NULL,
    tp_item_financeiro VARCHAR NOT NULL

    /*
    Caso decidam implementar o status como coluna gerada:

    status_item_financeiro VARCHAR(20) GENERATED ALWAYS AS (
        CASE
            WHEN dt_cancelamento IS NOT NULL THEN 'CANCELADO'
            WHEN dt_pagamento IS NOT NULL THEN 'PAGO'
