        END
    ) STORED
    */
);

CREATE TABLE tbl_regra_reembolso
(
    ce_evento INT NOT NULL,
    dt_limite_reembolso DATE NOT NULL,
    pct_devolucao NUMERIC(8,7) NOT NULL DEFAULT 1.0,

    PRIMARY KEY (ce_evento, dt_limite_reembolso)
);


